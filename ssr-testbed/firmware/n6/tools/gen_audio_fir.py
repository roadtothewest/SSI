#!/usr/bin/env python3
"""Coefficients of the ADMP401 decimation filter (plan 3): 64 kHz -> 16 kHz.

Linear-phase low-pass, windowed sinc with a Kaiser window, cut-off at 8 kHz, quantized to Q30
with the sum forced to exactly 2^30 (unity DC gain). Prints the C table for audio_fir.c and the
response at a few frequencies. Standard library only.

  gen_audio_fir.py            print the table and the response
"""
import math

FS, CUTOFF, TAPS, BETA = 64000.0, 8000.0, 97, 6.755
Q = 30


def i0(x):
    """Modified Bessel function of the first kind, order 0 (power series)."""
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2 * k)) ** 2
        s += term
        k += 1
    return s


def design():
    m = (TAPS - 1) / 2
    fc = CUTOFF / FS
    h = []
    for n in range(TAPS):
        t = n - m
        sinc = 2 * fc if t == 0 else math.sin(2 * math.pi * fc * t) / (math.pi * t)
        w = i0(BETA * math.sqrt(1 - (t / m) ** 2)) / i0(BETA)
        h.append(sinc * w)
    s = sum(h)
    return [v / s for v in h]


def quantize(h):
    q = [round(v * (1 << Q)) for v in h]
    q[TAPS // 2] += (1 << Q) - sum(q)  # exact unity DC gain
    return q


def response_db(q, f):
    re = sum(c * math.cos(2 * math.pi * f / FS * n) for n, c in enumerate(q))
    im = sum(c * math.sin(2 * math.pi * f / FS * n) for n, c in enumerate(q))
    return 20 * math.log10(math.hypot(re, im) / (1 << Q) + 1e-30)


def main():
    q = quantize(design())
    assert q == q[::-1], "not symmetric"
    print(f"/* Generated by tools/gen_audio_fir.py: {TAPS} taps, Kaiser beta {BETA}, cut-off {CUTOFF:.0f} Hz"
          f" at {FS:.0f} Hz, Q{Q}, sum = 2^{Q}. */")
    print(f"static const int32_t k_coef[AFIR_TAPS] = {{")
    for i in range(0, TAPS, 6):
        print("  " + ", ".join(f"{c}" for c in q[i:i + 6]) + ",")
    print("};")
    for f in (100, 1000, 4000, 6000, 6500, 7000, 8000, 9500, 12000, 16000, 24000, 31000):
        print(f"/* {f:6d} Hz: {response_db(q, f):7.2f} dB */")


if __name__ == "__main__":
    main()
